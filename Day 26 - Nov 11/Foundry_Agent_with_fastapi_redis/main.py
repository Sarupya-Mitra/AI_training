import os
import json
from dotenv import load_dotenv
from azure.identity import DefaultAzureCredential
from azure.ai.projects import AIProjectClient

from uuid import UUID, uuid4

import redis
from fastapi import FastAPI
from pydantic import BaseModel, Field
# 1. Get Configuration
load_dotenv()
app = FastAPI(title="Employee Leave Support Agent")
SESSION_TTL = 3600
# 2. cONNECT TO REDIS
db = redis.Redis.from_url(
    os.getenv("REDIS_URL"),
    decode_responses=True,
)


# 3. Connect to existing Microsoft Foundry agent
project = AIProjectClient(
    endpoint=os.environ["FOUNDRY_PROJECT_ENDPOINT"],
    credential=DefaultAzureCredential(),
    allow_preview=True
)

# Create client to communicate with agent
client = project.get_openai_client(
    agent_name=os.getenv("FOUNDRY_AGENT_NAME", "RetailSupportAgent")
)
# 4. Define request structure
class ChatRequest(BaseModel):
    message: str = Field(min_length=1,max_length=2000)
    session_id : UUID | None = None

# 5. Chat API
@app.post("/chat")
def chat(request: ChatRequest):
    session_id = str(request.session_id or uuid4())
    conversation_key = f"conversation_{session_id}" # Just a Redis key to look up a conversation
    history_key = f"history_{session_id}"
    # Get existing Foundry conversation from Redis
    conversation_id = db.get(conversation_key)
    # If there was not existing conversation, create new conversation
    if not conversation_id:
        conversation = client.conversations.create()
        conversation_id = conversation.id  # This id is generated by Foundry
        db.set(  # Saves the conversation details in Redis
            conversation_key,
            conversation_id,
            ex=SESSION_TTL # How long this key should live before expiration
        )
    # Call Foundry Agent
    response = client.responses.create(
        conversation=conversation_id,  # Sned the Foundry chat id to Foundry so that it continue
        # with that chat only and doesn't necessarily create new chat
        input = request.message
    )
    answer = response.output_text or ""
    with db.pipeline() as pipe:  # saving chat history in Redis
        # A Redis pipeline allows us to queue multiple Redis commands and execute them together
        pipe.rpush(
            history_key,
            json.dumps({
                "role":"user",
                "message":request.message,
            }),
            json.dumps({
                "role":"assistant",
                "message": answer
            })
        )

        pipe.expire(history_key, SESSION_TTL) # Set expiration time for history key
        pipe.expire(conversation_key, SESSION_TTL) # Set expiration time for conversation key
        pipe.execute() # Execute all queued Redis operations
    return {
        "session_id": session_id,
        "reply":answer
    }

# 6. Get Redis chat history
@app.get("/history/{session_id}")
def get_history(session_id : UUID):
    history_key = f"history_{session_id}"
    messages = db.lrange(history_key, 0, -1)
    return{
        "session_id": str(session_id),
        "messages": [
            json.loads(message)
            for message in messages
        ]
    }
